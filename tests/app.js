function detectPatterns(){
  const keep=[],improve=[];
  ['prog','cmd','trainee','env'].forEach(dim=>{
    DATA[dim].forEach((t,ti)=>{ if(!t.scored)return;
      const scores=S.frameworks.filter(f=>!isTopicNA(f.id,dim,ti)).map(f=>topicScore(t,(ci)=>fwCell(f.id,dim,ti,ci))).filter(v=>v!=null);
      if(scores.length<2)return;
      const avg=Math.round(scores.reduce((a,b)=>a+b,0)/scores.length);
      const lowN=scores.filter(s=>s<=70).length, highN=scores.filter(s=>s>=85).length;
      if(highN>=2&&avg>=85) keep.push({name:t.name+' · '+DIM_META[dim].short,avg,fw:highN});
      if(lowN>=2&&avg<=70) improve.push({name:t.name+' · '+DIM_META[dim].short,avg,fw:lowN});
    });
  });
  keep.sort((a,b)=>b.avg-a.avg); improve.sort((a,b)=>a.avg-b.avg);
  return {keep:keep.slice(0,6),improve:improve.slice(0,6)};
}
