/* עיבוד תוכן שדה ממצאים למבנה: שורת "## X" = כותרת נושא, "• Y" = בולט, אחר = שורה רגילה */
function findingsBlockHTML(txt){
  const raw=(txt||'').replace(/\s+$/,'');
  if(!raw.trim()) return '<p style="white-space:pre-line">—</p>';
  const lines=raw.split('\n');
  let html='', bulletsOpen=false, groupsOpen=false;
  const closeBul=()=>{ if(bulletsOpen){ html+='</ul>'; bulletsOpen=false; } };
  lines.forEach(line=>{
    const t=line.trim();
    if(!t){ closeBul(); return; }
    if(t.startsWith('## ') || ALL_TOPIC_NAMES.has(t)){   // כותרת נושא (כולל תוכן ישן ללא ##)
      closeBul();
      if(!groupsOpen){ html+='<div class="find-groups">'; groupsOpen=true; }
      html+=`<div class="find-topic">${esc(t.startsWith('## ')?t.slice(3).trim():t)}</div>`;
    } else if(t.startsWith('•')){                   // בולט
      if(!bulletsOpen){ html+='<ul class="find-ul">'; bulletsOpen=true; }
      html+=`<li>${esc(t.replace(/^•\s*/,''))}</li>`;
    } else {                                        // טקסט חופשי (עריכה ידנית)
      closeBul();
      html+=`<p class="find-line">${esc(t)}</p>`;
    }
  });
  closeBul();
  if(groupsOpen) html+='</div>';
  return html;
}
