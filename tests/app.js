function confirmRepl(cur,msg){ return !(cur&&cur.trim())||confirm(msg||'קיים תוכן בשדה. להחליפו בטיוטה המחוללת?'); }
function genOne(which){
  if(which==='summary'){ const v=genSummary(); if(!v){toast('יש להזין ציונים במסגרות לפני הניסוח');return;} if(!confirmRepl(S.report.summary))return; S.report.summary=v; }
  else if(which==='crossCut'){ const v=genCrossCut(); if(!v){toast('יש להזין ציונים במסגרות לפני הניסוח');return;} if(!confirmRepl(S.report.crossCut))return; S.report.crossCut=v; }
  else if(which==='directives'){ const lines=genDirectives(); if(!lines.length){toast('לא זוהו נושאים בציון נמוך הדורשים טיפול');return;}
    if(S.report.directives.some(d=>d.trim())&&!confirm('קיימות הנחיות שהוזנו. להחליפן בטיוטה המחוללת?'))return; S.report.directives=lines; }
  else if(which==='trends'){ const tr=genTrends(); if(!tr.keep&&!tr.improve){toast('טרם זוהו מגמות חוזרות (נדרשות שתי מסגרות ומעלה)');return;}
    if((S.report.trendsKeep+S.report.trendsImprove+S.report.recommendations).trim()&&!confirm('קיים תוכן בסקירת המגמות. להחליפו בטיוטה המחוללת?'))return;
    S.report.trendsKeep=tr.keep; S.report.trendsImprove=tr.improve; S.report.recommendations=tr.recs; }
  save(); render(); toast('נוסחה טיוטה — ניתנת לעריכה חופשית');
}
function genAll(){
  if(overallScore()==null){ toast('יש להזין ציונים במסגרות לפני הניסוח'); return; }
  const has=(S.report.summary+S.report.crossCut+S.report.trendsKeep+S.report.trendsImprove+S.report.recommendations).trim()||S.report.directives.some(d=>d.trim());
  if(has&&!confirm('לחולל טיוטות חדשות לכל הסעיפים? תוכן קיים בסעיפים אלו יוחלף.'))return;
  S.report.summary=genSummary();
  const dl=genDirectives(); if(dl.length) S.report.directives=dl;
  const tr=genTrends(); S.report.trendsKeep=tr.keep; S.report.trendsImprove=tr.improve; S.report.recommendations=tr.recs;
  save(); render(); toast('נוסחו טיוטות לכל הסעיפים — ניתנות לעריכה');
}

