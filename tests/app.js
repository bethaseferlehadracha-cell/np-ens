/* refresh just topic header score + dim bar without full rerender (keeps textareas focused) */
function refreshTopic(dimKey,ti){
  const topics = dimKey==='gph'?DATA.gph:DATA[dimKey];
  const t=topics[ti];
  const getter = dimKey==='gph'? gphCell : (a,b)=>fwCell(S.ui.activeFw,dimKey,a,b);
  let done=0,tot=0; t.crits.forEach((c,ci)=>{if(c.w==null)return;tot++;const cell=getter(ti,ci);if(cell&&cell.score!=null)done++;});
  const scope = dimKey==='gph' ? 'gph' : S.ui.activeFw;
  const ts=(t.scored&&!isTopicNA(scope,dimKey,ti))?topicScore(t,(ci)=>getter(ti,ci)):null; const b=band(ts);
  const el=document.getElementById('tp_'+dimKey+'_'+ti);
  if(el){ const sc=el.querySelector('.tscore'); const pr=el.querySelector('.tprog');
    if(sc&&t.scored){sc.className='tscore '+(b.k?'bg-'+b.k:''); sc.textContent=ts==null?'—':Math.round(ts);}
    if(pr)pr.textContent=done+'/'+tot;
    // refresh keep/improve tag + picker
    if(t.scored){
      const tag=el.querySelector('.ks-tag'); if(tag){ const nt=document.createElement('div'); nt.innerHTML=ksTagHTML(scope,dimKey,ti,ts); tag.replaceWith(nt.firstChild); }
      const pick=el.querySelector('.ks-picker'); if(pick){ const np=document.createElement('div'); np.innerHTML=ksPickerHTML(scope,dimKey,ti,ts); pick.replaceWith(np.firstChild); }
    }
    // refresh crit chip states in this topic
    t.crits.forEach((c,ci)=>{ if(c.w==null)return; const cell=getter(ti,ci); const cur=cell?cell.score:null;
      const crit=el.querySelectorAll('.crit')[ci]; if(!crit)return;
      crit.classList.toggle('filled',(cur!=null)||(cell&&cell.keep&&cell.keep.trim())||(cell&&cell.improve&&cell.improve.trim()));
      crit.querySelectorAll('.schip').forEach((chip,k)=>{ const pv=PRESETS[k].v; const on=cur===pv;
        chip.className='schip'+(on?(' on '+(pv>=80?'v-good':pv>=60?'v-mid':'v-low')):''); });
      const na=crit.querySelector('.score-na'); if(na)na.classList.toggle('on',cell&&cell.score===null&&cell.naMark);
      const kta=crit.querySelector('.kifield.keep textarea'); if(kta && document.activeElement!==kta) kta.value=cell&&cell.keep?cell.keep:'';
      const ita=crit.querySelector('.kifield.improve textarea'); if(ita && document.activeElement!==ita) ita.value=cell&&cell.improve?cell.improve:'';
      const cks=crit.querySelector('.critks'); if(cks){ const nb=document.createElement('div'); nb.innerHTML=critKsHTML(dimKey,ti,ci,cell); if(nb.firstChild)cks.replaceWith(nb.firstChild); }
    });
  }
  // refresh nav badge + dimbar
  renderNav();
  if(nav==='fw'){ document.querySelectorAll('.dimbar button').forEach((btn,i)=>{ const d=FW_DIMS[i]; const p=dimProgress((a,b)=>fwCell(S.ui.activeFw,d,a,b),DATA[d]);
    const mini=btn.querySelector('.mini'); if(mini)mini.textContent=`${p.done}/${p.tot}${p.pct===100?' ✓':''}`; btn.classList.toggle('done',p.pct===100); }); }
}

