/* סריקת כלל הממצאים שהוזנו — חטיבה + מסגרות × ממדים */
function scanFindings(){
  const out=[];
  DATA.gph.forEach((t,ti)=>{ if(!t.scored||isTopicNA('gph','gph',ti))return;
    const sc=topicScore(t,(ci)=>gphCell(ti,ci));
    const finds=[...new Set(t.crits.map((c,ci)=>{const cell=gphCell(ti,ci);return cell&&(cell.improve||cell.keep)?(cell.improve||cell.keep).trim():'';}).filter(Boolean))];
    if(sc==null&&!finds.length)return;
    out.push({dim:'gph',name:t.name,scope:'רמת החטיבה (גפ"ה)',score:sc,find:finds.join('; ')});
  });
  S.frameworks.forEach(f=>{
    FW_DIMS.forEach(dim=>{
      DATA[dim].forEach((t,ti)=>{ if(!t.scored||isTopicNA(f.id,dim,ti))return;
        const sc=topicScore(t,(ci)=>fwCell(f.id,dim,ti,ci));
        const finds=[...new Set(t.crits.map((c,ci)=>{const cell=fwCell(f.id,dim,ti,ci);return cell&&(cell.improve||cell.keep)?(cell.improve||cell.keep).trim():'';}).filter(Boolean))];
        if(sc==null&&!finds.length)return;
        out.push({dim,name:t.name,scope:(f.label||'מסגרת')+' · '+DIM_META[dim].short,score:sc,find:finds.join('; ')});
      });
    });
  });
  return out;
}

/* ====== איסוף סיווג שיפור/שימור לדוח ======
   scanKS(): כל נושא שדורג — עם סיווגו, ציונו, מקורו, נימוקו, ופירוט הקריטריונים שבו
   (כל קריטריון עם הסיווג העצמאי שלו). */
function ksReasonFor(dim,ti,getter){
  // מאחד את תוכן השימור/השיפור שהוזן בקריטריוני הנושא לטקסט אחד
  const t=(dim==='gph'?DATA.gph:DATA[dim])[ti];
  const keeps=[...new Set(t.crits.map((c,ci)=>{const cell=getter(ti,ci);return cell&&cell.keep?cell.keep.trim():'';}).filter(Boolean))];
  const improves=[...new Set(t.crits.map((c,ci)=>{const cell=getter(ti,ci);return cell&&cell.improve?cell.improve.trim():'';}).filter(Boolean))];
  return {keep:keeps.join(' '), improve:improves.join(' ')};
}
/* פירוט הקריטריונים בנושא, כל אחד עם הסיווג העצמאי שלו */
function topicCrits(dim,ti,getter){
  const t=(dim==='gph'?DATA.gph:DATA[dim])[ti];
  const out=[];
  t.crits.forEach((c,ci)=>{
    if(c.w==null)return; // דילוג על סעיפים איכותיים
    const cell=getter(ti,ci); if(!cell)return;
    const keep=cell.keep?cell.keep.trim():'';
    const improve=cell.improve?cell.improve.trim():'';
    if(cell.score==null && !keep && !improve)return;
    out.push({ci,score:cell.score,cls:critKsClass(cell),keep,improve});
  });
  return out;
}
function scanKS(){
  const out=[];
  // רמת החטיבה
  DATA.gph.forEach((t,ti)=>{ if(!t.scored||isTopicNA('gph','gph',ti))return;
    const sc=topicScore(t,(ci)=>gphCell(ti,ci)); if(sc==null)return;
    const cls=ksAuto(sc); if(!cls)return;
    const r=ksReasonFor('gph',ti,gphCell);
    out.push({scope:'gph',dim:'gph',ti,name:t.name,area:'רמת החטיבה (גפ"ה)',score:sc,cls,
      keepTxt:r.keep,improveTxt:r.improve,crits:topicCrits('gph',ti,gphCell)});
  });
  // רמת המסגרות × ממדים
  S.frameworks.forEach(f=>{
    FW_DIMS.forEach(dim=>{
      DATA[dim].forEach((t,ti)=>{ if(!t.scored||isTopicNA(f.id,dim,ti))return;
        const sc=topicScore(t,(ci)=>fwCell(f.id,dim,ti,ci)); if(sc==null)return;
        const cls=ksAuto(sc); if(!cls)return;
        const r=ksReasonFor(dim,ti,(a,b)=>fwCell(f.id,dim,a,b));
        out.push({scope:f.id,dim,ti,name:t.name,area:(f.label||'מסגרת')+' · '+DIM_META[dim].short,
          score:sc,cls,keepTxt:r.keep,improveTxt:r.improve,
          crits:topicCrits(dim,ti,(a,b)=>fwCell(f.id,dim,a,b))});
      });
    });
  });
  return out;
}
/* ====== ריכוז שיפור/שימור אוטומטי לדו"ח ======
   מקור יחיד לאמת: הציון הסופי של כל נושא (topicScore).
     ציון <  KS_THRESHOLD  =>  שיפור
     ציון >= KS_THRESHOLD  =>  שימור
   נושא נכלל אך ורק אם יש לו ציון מחושב — נושא איכותי (scored=false),
   נושא שסומן "לא רלוונטי", או נושא שטרם דורג, אינם מופיעים באף רשימה. */
function ksBuckets(){
  const all=scanKS();
  const bySide=cls=>all.filter(x=>x.cls===cls).sort((a,b)=>a.score-b.score||a.name.localeCompare(b.name,'he'));
  return {improve:bySide('improve'), keep:bySide('keep')};
}
function ksEntryHTML(x){
  const b=band(x.score);
  const side=x.cls;                       // 'keep' | 'improve'
  // פירוט הקריטריונים שנכתב להם טקסט בצד המתאים, ללא כפילויות
  const seen=new Set(), crits=[];
  (x.crits||[]).forEach(c=>{ const txt=(side==='keep'?c.keep:c.improve); if(!txt) return;
    const t=txt.trim(); if(!t||seen.has(t))return; seen.add(t); crits.push({score:c.score,t}); });
  // אם לא נכתב פירוט ברמת הקריטריון — מוצג הטקסט המאוחד של הנושא
  const fallback = crits.length ? '' : (side==='keep' ? x.keepTxt : x.improveTxt);
  return `<div class="ks-entry">
    <div class="kh"><b>${esc(x.name)}</b><span class="area">${esc(x.area)}</span>
      <span class="sc ${b.k?'bg-'+b.k:''}">${Math.round(x.score)}</span></div>
    ${fallback?`<div class="kr">${esc(fallback)}</div>`:''}
    ${crits.length?`<div class="ks-crits">${crits.map(c=>`<div class="ks-crit"><span class="ctxt">${
      c.score!=null?`<span class="cscore">${Math.round(c.score)}</span> `:''}${esc(c.t)}</span></div>`).join('')}</div>`:''}
  </div>`;
}
function ksColHTML(cls,items){
  const title = cls==='keep' ? 'שימור' : 'שיפור';
  const rule  = cls==='keep' ? `ציון ${KS_THRESHOLD} ומעלה` : `ציון נמוך מ-${KS_THRESHOLD}`;
  const ic    = cls==='keep' ? '<path d="M20 6L9 17l-5-5"/>' : '<path d="M12 20V10M6 20V4M18 20v-7"/>';
  return `<div class="ks-col ${cls}">
    <h4>${svg(ic)}${title}<span class="cnt">${items.length}</span></h4>
    ${items.length ? items.map(ksEntryHTML).join('')
                   : `<p class="ks-empty">אין נושאים ב${rule}.</p>`}
  </div>`;
}
/* הבלוק המלא — משמש גם במחולל הדוחות וגם בדו"ח המופק */
function ksReportHTML(){
  const bk=ksBuckets();
  if(!bk.improve.length && !bk.keep.length)
    return '<p class="ks-empty">טרם הוזנו ציונים — ריכוז השיפור/שימור ייבנה אוטומטית עם הזנת הציונים.</p>';
  return `<div class="ks-report">${ksColHTML('improve',bk.improve)}${ksColHTML('keep',bk.keep)}</div>`;
}
