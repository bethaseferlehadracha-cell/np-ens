/* הנחיות לטיפול מיידי — מתוך הממצאים החלשים, מתועדפות */
function genDirectives(){
  const items=scanFindings().filter(x=>x.score!=null&&x.score<=69);
  items.sort((a,b)=>a.score-b.score);
  return items.map(x=>{
    const kb=kbOf(x.dim,x.name);
    const tag=x.score<60?'טיפול מיידי':'לטיפול';
    const fnd=x.find?` נמצא: ${x.find}.`:'';
    const ref=kb.ref?` (נוהל ${kb.ref})`:'';
    return `[${tag}] ${x.name} — ${x.scope} (ציון ${Math.round(x.score)}):${fnd} נדרש ${kb.fix}${ref}.`;
  });
}

/* סקירת מגמות — שימור / שיפור / המלצות, מתוך המאפיינים החוזרים */
function genTrends(){
  const p=detectPatterns();
  const keep=p.keep.length
    ? p.keep.map(x=>`• ${x.name} — נשמר ברמה גבוהה (ממוצע ${x.avg}) ב-${x.fw} מסגרות.`).join('\n') : '';
  const improve=p.improve.length
    ? p.improve.map(x=>`• ${x.name} — חוזר כפער ב-${x.fw} מסגרות (ממוצע ${x.avg}).`).join('\n') : '';
  const recs=p.improve.map(x=>{
    const parts=x.name.split(' · '); const name=parts[0]; const dim=SHORT2DIM[parts[1]]||'prog';
    const kb=kbOf(dim,name);
    return `• ${name}: ${kb.fix}${kb.ref?` (נוהל ${kb.ref})`:''}.`;
  }).join('\n');
  return {keep,improve,recs};
}

